create table if not exists public.learning_records (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 record_type text not null check (record_type in ('visit','quiz','ai','note')),
 payload jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
alter table public.learning_records enable row level security;
drop policy if exists "Users read own learning records" on public.learning_records;
create policy "Users read own learning records" on public.learning_records for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users insert own learning records" on public.learning_records;
create policy "Users insert own learning records" on public.learning_records for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users delete own learning records" on public.learning_records;
create policy "Users delete own learning records" on public.learning_records for delete to authenticated using (auth.uid() = user_id);
grant select, insert, delete on public.learning_records to authenticated;
grant usage, select on sequence public.learning_records_id_seq to authenticated;
